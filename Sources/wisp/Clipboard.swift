import AppKit
import Foundation
import WispCommon

/// What one side sends: one pasteboard item's representations (UTI, bytes), in order of preference.
struct ClipboardPayload {
    var reps: [(type: String, data: Data)]
    var total: Int { reps.reduce(0) { $0 + $1.data.count } }
    /// "public.utf8-plain-text 12 B, public.rtf 340 B", for the log (never the contents).
    var summary: String { reps.map { "\($0.type) \($0.data.count) B" }.joined(separator: ", ") }

    /// clipboardBegin's payload after the id: u32 total, u8 n, n x (str UTI, u32 bytes).
    func header(_ w: inout Writer) {
        w.u32(UInt32(total)); w.u8(UInt8(reps.count))
        for r in reps { w.str(r.type); w.u32(UInt32(r.data.count)) }
    }
}

/// Clipboard sync with the peer of one connection (the viewer's host, or the host's viewer), both ways.
///
/// While connected it polls this side's pasteboard (`changeCount`, every 0.4 s). A change that we didn't
/// make ourselves is read (the first item: plain text, RTF, HTML, PNG — TIFF converted to PNG — and
/// URLs, also as text), and sent to the peer in a `clipboardBegin` header and `clipboardChunk`s of at
/// most 60000 B, at most two chunks in the connection's send queue at a time so input and other control
/// messages never wait behind megabytes. A newer change abandons a transfer still in flight. What the
/// peer sends is written to this side's pasteboard, with a marker type (`markerType`); a change that
/// carries the marker, or whose changeCount is the one our write produced, is never sent back: no echo
/// loop, even when both ends share one pasteboard (loopback on one Mac). Last writer wins.
///
/// Never sent: items marked concealed, transient or auto-generated (what password managers set: see
/// nspasteboard.org), files (public.file-url; not in this version), anything over `maxBytes` (the
/// representations that don't fit are left out, cheapest first). Only to a peer that announced
/// `Wire.Feature.clipboard` and says it's on (`clipboardState`); nothing while this side's setting is
/// off. The log has types and sizes (debug), never contents.
///
/// Main queue only. The owner calls `connected(peerSupports:)`, `receive(_:_:)` and `disconnected()`
/// on the main queue; `send` may be called from it on the main queue, and calls its completion when the
/// message has left (any queue).
final class ClipboardSync {
    enum Side: String { case host, viewer }

    /// The defaults keys of the two settings ("Share clipboard with remote Macs" / "… with viewers"), both on by default.
    static let viewerKey = "shareClipboardWithHosts"
    static let hostKey = "shareClipboardWithViewers"
    /// Most bytes sent or accepted per clipboard (defaults key, else 10 MB; WISP_CLIPBOARD_MAX for tests).
    static let maxBytesKey = "clipboardMaxBytes"
    static let defaultMaxBytes = 10 << 20
    /// Written with every item we put on the pasteboard, so it isn't sent back (see the class comment).
    static let markerType = NSPasteboard.PasteboardType("app.wisp.clipboard-sync")
    /// Types nspasteboard.org reserves for data that shouldn't leave the Mac or go into clipboard history.
    static let privateTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                            "org.nspasteboard.AutoGeneratedType"]
    static let chunkBytes = 60000

    /// The pasteboard to sync: the general one, or a private named one (WISP_PASTEBOARD=<name>, for tests,
    /// so a test never touches the real clipboard).
    static var defaultPasteboard: NSPasteboard {
        if let name = ProcessInfo.processInfo.environment["WISP_PASTEBOARD"], !name.isEmpty {
            return NSPasteboard(name: NSPasteboard.Name(name))
        }
        return .general
    }
    /// A test chose a private pasteboard (the CLI's test commands sync only then).
    static var isTestPasteboard: Bool { !(ProcessInfo.processInfo.environment["WISP_PASTEBOARD"] ?? "").isEmpty }

    let side: Side
    let pasteboard: NSPasteboard
    /// This side's setting, read on every poll (a change is told to the peer).
    var isEnabled: () -> Bool
    var maxBytes: Int
    private let send: (Data, @escaping () -> Void) -> Void

    private var peerName: String { side == .host ? "viewer" : "host" }
    private var beginType: MsgType { side == .host ? .hostClipboardBegin : .clipboardBegin }
    private var chunkType: MsgType { side == .host ? .hostClipboardChunk : .clipboardChunk }
    private var stateType: MsgType { side == .host ? .hostClipboardState : .clipboardState }

    private var timer: DispatchSourceTimer?
    private var peerSupports = false
    private var peerOn = false
    private var wasEnabled: Bool?
    private var lastSeen = 0       // the pasteboard's changeCount at the last poll
    private var ourWrite = -1      // the changeCount our last write produced
    private var nextID: UInt32 = 1
    // Sending: the transfer in progress and how many of its chunks are queued on the connection.
    private var out: (id: UInt32, data: Data, offset: Int, queued: Int)?
    // Receiving: the transfer being put together.
    private var incoming: (id: UInt32, types: [(String, Int)], total: Int, data: Data)?
    /// Messages sent and clipboards applied this connection (for the disconnect line and tests).
    private(set) var sentCount = 0, receivedCount = 0

    init(side: Side, pasteboard: NSPasteboard = ClipboardSync.defaultPasteboard, send: @escaping (Data, @escaping () -> Void) -> Void) {
        self.side = side
        self.pasteboard = pasteboard
        let key = side == .host ? Self.hostKey : Self.viewerKey
        isEnabled = { Brand.defaults.object(forKey: key) as? Bool ?? true }
        if let env = ProcessInfo.processInfo.environment["WISP_CLIPBOARD_MAX"].flatMap(Int.init) {
            maxBytes = env
        } else if let v = Brand.defaults.object(forKey: Self.maxBytesKey) as? Int, v > 0 {
            maxBytes = v
        } else {
            maxBytes = Self.defaultMaxBytes
        }
        self.send = send
    }

    // MARK: Connection

    /// The hello exchange is done: start polling, and tell the peer whether we're on (if it can sync).
    func connected(peerSupports: Bool) {
        stopTimer()
        self.peerSupports = peerSupports
        peerOn = false
        out = nil; incoming = nil
        sentCount = 0; receivedCount = 0
        lastSeen = pasteboard.changeCount // what's on the clipboard already isn't sent: only new copies
        let on = isEnabled()
        wasEnabled = on
        guard peerSupports else {
            Log.info(.clipboard, "sync: the \(peerName) doesn't do clipboard sync (an older \(Brand.name), or sync not set up there): off for this connection")
            return
        }
        Log.info(.clipboard, "sync with the \(peerName): \(on ? "on" : "off (this Mac's setting)")"
                 + "; up to \(Self.size(maxBytes))\(pasteboard.name == .general ? "" : ", pasteboard \"\(pasteboard.name.rawValue)\"")")
        sendState(on)
        let t = DispatchSource.makeTimerSource(queue: .main)
        t.schedule(deadline: .now() + 0.4, repeating: 0.4, leeway: .milliseconds(50))
        t.setEventHandler { [weak self] in self?.poll() }
        t.resume()
        timer = t
    }

    /// "10 MB", "2.9 MB", "512 KB".
    static func size(_ n: Int) -> String {
        n >= 1 << 20 ? String(format: n % (1 << 20) == 0 ? "%.0f MB" : "%.1f MB", Double(n) / Double(1 << 20)) : "\(n / 1024) KB"
    }

    func disconnected() {
        guard timer != nil || peerSupports else { return }
        if peerSupports { Log.info(.clipboard, "sync with the \(peerName) ended: \(sentCount) sent, \(receivedCount) received") }
        stopTimer()
        peerSupports = false; peerOn = false
        out = nil; incoming = nil
    }

    private func stopTimer() { timer?.cancel(); timer = nil }

    private func sendState(_ on: Bool) { send(message(stateType) { $0.u8(on ? 1 : 0) }) {} }

    // MARK: Sending

    private func poll() {
        let on = isEnabled()
        if on != wasEnabled {
            wasEnabled = on
            Log.info(.clipboard, "sync with the \(peerName) turned \(on ? "on" : "off") (this Mac's setting)")
            sendState(on)
            if !on { out = nil; incoming = nil }
            lastSeen = pasteboard.changeCount // a copy made while off isn't sent later
        }
        let count = pasteboard.changeCount
        guard count != lastSeen else { return }
        lastSeen = count
        guard count != ourWrite else { return } // our own write
        guard on else { return }
        guard peerOn else { Log.debug(.clipboard, "changed: not sent, the \(peerName) has clipboard sync off"); return }
        guard let payload = read() else { return }
        start(payload)
    }

    /// The pasteboard's first item as we send it, or nil (logged) if it must not or cannot be sent.
    private func read() -> ClipboardPayload? {
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        if types.contains(Self.markerType.rawValue) { return nil } // written by a sync (ours, or the peer's on this Mac)
        if let p = types.first(where: Self.privateTypes.contains) {
            Log.debug(.clipboard, "changed: not sent, marked private (\(p))")
            return nil
        }
        guard let item = pasteboard.pasteboardItems?.first else { return nil }
        let itemTypes = item.types.map(\.rawValue)
        if itemTypes.contains(NSPasteboard.PasteboardType.fileURL.rawValue) {
            Log.info(.clipboard, "changed: not sent, files aren't synced (yet)")
            return nil
        }
        var reps: [(String, Data)] = []
        func add(_ t: NSPasteboard.PasteboardType) {
            if itemTypes.contains(t.rawValue), let d = item.data(forType: t) { reps.append((t.rawValue, d)) }
        }
        add(.string)
        add(.rtf)
        add(.html)
        if itemTypes.contains(NSPasteboard.PasteboardType.png.rawValue) {
            add(.png)
        } else if itemTypes.contains(NSPasteboard.PasteboardType.tiff.rawValue), let tiff = item.data(forType: .tiff) {
            // TIFF is usually uncompressed: PNG is a fraction of the bytes.
            if let png = NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:]) {
                reps.append((NSPasteboard.PasteboardType.png.rawValue, png))
            } else {
                Log.debug(.clipboard, "a TIFF image that can't be converted to PNG (\(tiff.count) B): left out")
            }
        }
        if itemTypes.contains(NSPasteboard.PasteboardType.URL.rawValue), let s = item.string(forType: .URL),
           let url = URL(string: s), !url.isFileURL {
            reps.append((NSPasteboard.PasteboardType.URL.rawValue, Data(s.utf8)))
            if !reps.contains(where: { $0.0 == NSPasteboard.PasteboardType.string.rawValue }) {
                reps.insert((NSPasteboard.PasteboardType.string.rawValue, Data(s.utf8)), at: 0)
            }
        }
        guard !reps.isEmpty else {
            Log.debug(.clipboard, "changed: nothing we sync (types: \(itemTypes.prefix(8).joined(separator: ", ")))")
            return nil
        }
        // Over the cap: keep what fits, in order (text first, images last).
        var kept: [(type: String, data: Data)] = [], total = 0, skipped: [String] = []
        for r in reps {
            if total + r.1.count <= maxBytes { kept.append((r.0, r.1)); total += r.1.count } else { skipped.append("\(r.0) \(r.1.count) B") }
        }
        if !skipped.isEmpty {
            Log.info(.clipboard, "over the \(Self.size(maxBytes)) limit, left out: \(skipped.joined(separator: ", "))"
                     + (kept.isEmpty ? "; nothing sent" : ""))
        }
        return kept.isEmpty ? nil : ClipboardPayload(reps: kept)
    }

    private func start(_ p: ClipboardPayload) {
        let id = nextID
        nextID &+= 1
        if let o = out, o.offset < o.data.count {
            Log.debug(.clipboard, "#\(o.id) abandoned at \(o.offset) of \(o.data.count) B: a newer copy replaces it")
        }
        var data = Data(capacity: p.total)
        p.reps.forEach { data.append($0.data) }
        let chunks = (data.count + Self.chunkBytes - 1) / Self.chunkBytes
        Log.debug(.clipboard, "#\(id) → \(peerName): \(p.summary) (\(data.count) B in \(chunks) chunk\(chunks == 1 ? "" : "s"))")
        sentCount += 1
        send(message(beginType) { $0.u32(id); p.header(&$0) }) {}
        out = (id, data, 0, 0)
        pump()
    }

    /// Queues the current transfer's next chunks, at most two at a time on the connection.
    private func pump() {
        while var o = out, o.offset < o.data.count, o.queued < 2 {
            let end = min(o.offset + Self.chunkBytes, o.data.count)
            let part = o.data.subdata(in: o.offset ..< end)
            let msg = message(chunkType) { $0.u32(o.id); $0.u32(UInt32(o.offset)); $0.bytes(part) }
            o.offset = end
            o.queued += 1
            out = o
            let id = o.id
            send(msg) { [weak self] in
                DispatchQueue.main.async {
                    guard let self, var o = self.out, o.id == id else { return }
                    o.queued -= 1
                    self.out = o
                    self.pump()
                }
            }
        }
        if let o = out, o.offset >= o.data.count, o.queued == 0 { out = nil }
    }

    // MARK: Receiving

    /// A clipboard message from the peer (either direction's types).
    func receive(_ t: MsgType, _ p: Data) {
        var r = Reader(p)
        switch t {
        case .clipboardState, .hostClipboardState:
            let on = (r.u8() ?? 0) != 0
            if on != peerOn { Log.info(.clipboard, "the \(peerName) \(on ? "shares" : "doesn't share") its clipboard") }
            peerOn = on
            if !on { out = nil }
        case .clipboardBegin, .hostClipboardBegin:
            guard let id = r.u32(), let total = r.u32().map(Int.init), let n = r.u8() else { return }
            var types: [(String, Int)] = []
            for _ in 0 ..< n {
                guard let s = r.str(), let len = r.u32() else { return }
                types.append((s, Int(len)))
            }
            if let old = incoming { Log.debug(.clipboard, "#\(old.id) from the \(peerName) replaced by #\(id) before it was complete") }
            incoming = nil
            guard peerSupports, wasEnabled == true else {
                Log.debug(.clipboard, "#\(id) from the \(peerName) ignored: sync is off here"); return
            }
            guard types.reduce(0, { $0 + $1.1 }) == total else { Log.warning(.clipboard, "#\(id) from the \(peerName): sizes don't add up; ignored"); return }
            guard total <= maxBytes else {
                Log.info(.clipboard, "#\(id) from the \(peerName) is \(total) B, over this Mac's \(Self.size(maxBytes)) limit: ignored"); return
            }
            incoming = (id, types, total, Data(capacity: total))
            if total == 0 { finishIncoming() }
        case .clipboardChunk, .hostClipboardChunk:
            guard let id = r.u32(), let offset = r.u32(), var inc = incoming, inc.id == id else { return }
            guard Int(offset) == inc.data.count else {
                Log.warning(.clipboard, "#\(id) from the \(peerName): chunk out of order; dropped"); incoming = nil; return
            }
            inc.data.append(r.rest())
            guard inc.data.count <= inc.total else { Log.warning(.clipboard, "#\(id): more bytes than announced; dropped"); incoming = nil; return }
            incoming = inc
            if inc.data.count == inc.total { finishIncoming() }
        default: break
        }
    }

    private func finishIncoming() {
        guard let inc = incoming else { return }
        incoming = nil
        let item = NSPasteboardItem()
        var offset = inc.data.startIndex
        var summary: [String] = []
        for (type, len) in inc.types {
            let d = inc.data.subdata(in: offset ..< offset + len)
            offset += len
            // Never take a type that asks for special treatment from the peer (or a marker we'd misread).
            guard !Self.privateTypes.contains(type), type != Self.markerType.rawValue,
                  type != NSPasteboard.PasteboardType.fileURL.rawValue else { continue }
            item.setData(d, forType: NSPasteboard.PasteboardType(type))
            summary.append("\(type) \(len) B")
        }
        item.setData(Data(), forType: Self.markerType)
        pasteboard.clearContents()
        guard pasteboard.writeObjects([item]) else {
            Log.warning(.clipboard, "#\(inc.id) from the \(peerName): the pasteboard refused it")
            return
        }
        ourWrite = pasteboard.changeCount
        lastSeen = ourWrite
        receivedCount += 1
        // A copy of ours still going out is now older than what's on the clipboard: stop it.
        out = nil
        Log.debug(.clipboard, "#\(inc.id) ← \(peerName): \(summary.joined(separator: ", ")) (\(inc.total) B)")
    }
}
